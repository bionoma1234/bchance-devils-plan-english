import assert from 'node:assert/strict';
import {webcrypto} from 'node:crypto';
globalThis.crypto ??= webcrypto;
const {JAK_GAMES,isJak,createJakMatch,actJak,advanceJakIfDue,viewJak}=await import('../src/jakbox.js');
const people=n=>Array.from({length:n},(_,i)=>({id:'person-'+i,name:'Player '+i}));
const strokes=[[[10,20],[40,50],[70,80]]];
assert.equal(Object.keys(JAK_GAMES).length,5);
assert.equal(isJak('jak:tee'),true);
assert.equal(isJak('square'),false);
assert.throws(()=>createJakMatch('jak:clash',people(2)),/requires/);
assert.throws(()=>createJakMatch('jak:tee',people(9)),/requires/);
const clash=createJakMatch('jak:clash',people(3));
assert.equal(clash.phase,'write');
const [a,b]=clash.contestants,c=clash.ids.find(id=>!clash.contestants.includes(id));
assert.equal(actJak(clash,a,{type:'write',text:'Ridiculous answer A'}),true);
assert.equal(actJak(clash,b,{type:'write',text:'Ridiculous answer B'}),true);
assert.equal(clash.phase,'vote');
assert.deepEqual(Object.keys(viewJak(clash,c).options[0]).sort(),['id','text']);
assert.equal(clash.options[0].id===a,false);
assert.equal(actJak(clash,a,{type:'vote',choice:clash.options[0].id}),false);
assert.equal(actJak(clash,c,{type:'vote',choice:clash.options[0].id}),true);
assert.equal(clash.phase,'result');
assert.ok(clash.points[clash.options[0].author]>0);
assert.equal(actJak(clash,a,{type:'next'}),true);
assert.equal(clash.round,2);
const bluff=createJakMatch('jak:bluff',people(3));
assert.equal(bluff.phase,'lie');
for(let i=0;i<3;i++)assert.equal(actJak(bluff,'person-'+i,{type:'write',text:'Fake Fact '+i}),true);
assert.equal(bluff.phase,'vote');
const bluffView=viewJak(bluff,'person-0');
assert.equal(Object.hasOwn(bluffView,'truth'),false);
assert.ok(bluffView.options.every(o=>!Object.hasOwn(o,'kind')&&!Object.hasOwn(o,'author')));
assert.ok(bluffView.options.every(o=>o.id!=='truth'&&!o.id.startsWith('lie:')));
const truthful=bluff.options.find(o=>o.kind==='truth');
const own=bluff.options.find(o=>o.author==='person-0');
assert.equal(bluffView.blockedOptionId,own.id);
assert.equal(actJak(bluff,'person-0',{type:'vote',choice:own.id}),false);
assert.equal(actJak(bluff,'person-0',{type:'vote',choice:truthful.id}),true);
assert.equal(actJak(bluff,'person-1',{type:'vote',choice:truthful.id}),true);
assert.equal(actJak(bluff,'person-2',{type:'vote',choice:bluff.options.find(o=>o.author==='person-0').id}),true);
assert.equal(bluff.phase,'result');
assert.equal(bluff.points['person-0'],750);
assert.equal(bluff.points['person-1'],500);
assert.equal(viewJak(bluff,'person-0').truth,bluff.item.truth);
const draw=createJakMatch('jak:draw',people(3));
const artist=draw.artist,guests=draw.ids.filter(id=>id!==artist);
assert.equal(viewJak(draw,guests[0]).prompt,undefined);
assert.equal(actJak(draw,artist,{type:'art',strokes:[[[1001,1],[10,10]]]}),false);
assert.equal(actJak(draw,artist,{type:'art',strokes}),true);
assert.equal(draw.phase,'fake');
assert.equal(viewJak(draw,guests[0]).prompt,undefined);
for(const [i,id] of guests.entries())assert.equal(actJak(draw,id,{type:'write',text:'Title '+i}),true);
assert.equal(draw.phase,'vote');
const drawView=viewJak(draw,guests[0]);
assert.equal(drawView.prompt,undefined);
assert.equal(drawView.options.some(o=>Object.hasOwn(o,'kind')),false);
assert.equal(actJak(draw,guests[0],{type:'vote',choice:drawView.blockedOptionId}),false);
const trueTitle=draw.options.find(o=>o.kind==='truth');
for(const id of guests)assert.equal(actJak(draw,id,{type:'vote',choice:trueTitle.id}),true);
assert.equal(draw.phase,'result');
assert.equal(draw.points[artist],300);
assert.equal(viewJak(draw,guests[0]).prompt,draw.prompt);
const split=createJakMatch('jak:split',people(5));
assert.equal(actJak(split,split.author,{type:'write',text:'a singing pineapple'}),true);
assert.equal(split.phase,'vote');
const others=split.ids.filter(id=>id!==split.author);
assert.equal(actJak(split,split.author,{type:'vote',choice:'yes'}),false);
for(const [i,id] of others.entries())assert.equal(actJak(split,id,{type:'vote',choice:i<2?'yes':'no'}),true);
assert.equal(split.phase,'result');
assert.equal(split.points[split.author],700);
const tee=createJakMatch('jak:tee',people(3));
assert.equal(tee.phase,'draw');
for(const id of tee.ids)assert.equal(actJak(tee,id,{type:'art',strokes}),true);
assert.equal(tee.phase,'slogan');
for(const [i,id] of tee.ids.entries())assert.equal(actJak(tee,id,{type:'slogan',text:'Shirt text '+i}),true);
assert.equal(tee.phase,'compose');
for(const id of tee.ids)assert.equal(actJak(tee,id,{type:'compose',artId:id,sloganId:id}),true);
assert.equal(tee.phase,'battle');
assert.equal(viewJak(tee,'person-0').art['person-0'][0].length,3);
const otherVoter=tee.ids.find(id=>!tee.battlePair.includes(id));
assert.equal(actJak(tee,tee.battlePair[0],{type:'vote',choice:tee.battlePair[0]}),false);
assert.equal(actJak(tee,otherVoter,{type:'vote',choice:tee.battlePair[0]}),true);
assert.equal(tee.phase,'result');
assert.equal(tee.points[tee.battlePair[0]],800);
for(let i=2;i<=tee.ids.length;i++){
 assert.equal(actJak(tee,'person-0',{type:'next'}),true);
 assert.equal(tee.phase,'battle');
 const voter=tee.ids.find(id=>!tee.battlePair.includes(id));
 assert.equal(actJak(tee,voter,{type:'vote',choice:tee.battlePair[1]}),true);
 assert.equal(tee.phase,'result');
}
assert.equal(actJak(tee,'person-0',{type:'next'}),true);
assert.equal(tee.phase,'complete');
assert.ok(tee.winnerIds.length>0);
const due=createJakMatch('jak:draw',people(3));
assert.equal(advanceJakIfDue(due,due.deadline),true);
assert.equal(due.phase,'fake');
assert.equal(advanceJakIfDue(due,due.deadline),true);
assert.equal(due.phase,'vote');
assert.equal(advanceJakIfDue(due,due.deadline),true);
assert.equal(due.phase,'result');
console.log('PASS: five JakBox engines, anonymous bluff choices, real-truth secrecy, drawings, scores, voting, timeouts and shirt creation');
